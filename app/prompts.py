def build_user_prompt(
    family_profile: str | None = None,
    output_language: str | None = None,
) -> str:
    target_language = output_language_prompt_name(output_language)
    language_instruction = f"""
本次用户选择的输出语言是：{target_language}。
非常重要：JSON 里所有给用户看的自然语言内容都必须使用 {target_language}。
上面的中文规则和 JSON 示例只是字段说明，不代表输出语言。
除非目标语言是 Simplified Chinese，否则不要输出中文短句；品牌名、包装原文、数字和单位可以保留。
""".strip()

    final_language_guard = f"""
最终检查：请只输出 JSON。所有字段值必须面向 {target_language} 用户阅读。
需要跟随目标语言的字段包括 verdict、item_name、category、subtitle、what_it_is、how_to_use、benefit、warning、storage、voice_summary、needs_more_photo。
不要把中文示例词（如“可以买/看情况/怎么用/注意”）原样输出，除非目标语言是 Simplified Chinese。
""".strip()

    if not family_profile:
        return f"{language_instruction}\n\n{USER_PROMPT}\n\n{final_language_guard}"

    return f"""
{language_instruction}

已知用户补充了家庭情况，请只作为轻量提醒背景，不要做医疗诊断：
{family_profile}

{USER_PROMPT}

{final_language_guard}
""".strip()
